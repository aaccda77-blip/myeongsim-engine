    // ========================================================================
    // 생체 신호 트리거 판단
    // ========================================================================
    static shouldTrigger(heartRate?: number, hrv?: number): boolean {
        if (heartRate && heartRate > 95) return true;    // 심박수 급증
        if (hrv && hrv < 30) return true;                // HRV 급감 (스트레스)
        return false;
    }

    // ========================================================================
    // 사용자 메시지에서 핵심 두려움 패턴 감지
    // ========================================================================
    static detectFearPattern(userMessage: string, sajuTenGods?: string[]): CoreFearProfile | null {
        // 1순위: 사주 십신 기반 매칭
        if (sajuTenGods && sajuTenGods.length > 0) {
            for (const god of sajuTenGods) {
                const profile = this.FEAR_PROFILES.find(p => p.sajuPattern === god);
                if (profile) {
                    const regex = new RegExp(profile.triggerKeyword, 'i');
                    if (regex.test(userMessage)) return profile;
                }
            }
        }

        // 2순위: 키워드 기반 범용 매칭
        for (const profile of this.FEAR_PROFILES) {
            const regex = new RegExp(profile.triggerKeyword, 'i');
            if (regex.test(userMessage)) return profile;
        }

        return null;
    }

