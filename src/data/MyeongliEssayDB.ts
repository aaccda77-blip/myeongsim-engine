// 매칭 헬퍼 함수
export function getMyeongliEssay(termKey: string): MyeongliEssay | null {
    if (!termKey) return null;
    
    // 이미 접두사가 붙어 있는 경우 (예: 'gan_갑') 그대로 반환 시도
    if (MYEONGLI_ESSAY_DB[termKey]) {
        return MYEONGLI_ESSAY_DB[termKey];
    }
    
    // 접두사 없이 들어왔을 때 유연한 매핑 (하위 호환성 및 단순 조회용)
    // 괄호 및 안의 내용, 공백 제거 후 소문자 변환
    let cleanKey = termKey.trim().replace(/\s*\(.*\)\s*/g, '').toLowerCase();
    
    // 1. 천간 체크
    const ganMap: Record<string, string> = {
        '甲': 'gan_갑', '갑목': 'gan_갑', '갑': 'gan_갑',
        '乙': 'gan_을', '을목': 'gan_을', '을': 'gan_을',
        '丙': 'gan_병', '병화': 'gan_병', '병': 'gan_병',
        '丁': 'gan_정', '정화': 'gan_정', '정': 'gan_정',
        '戊': 'gan_무', '무토': 'gan_무', '무': 'gan_무',
        '己': 'gan_기', '기토': 'gan_기', '기': 'gan_기',
        '庚': 'gan_경', '경금': 'gan_경', '경': 'gan_경',
        '辛': 'gan_신', '신금': 'gan_신', '신': 'gan_신',
        '壬': 'gan_임', '임수': 'gan_임', '임': 'gan_임',
        '癸': 'gan_계', '계수': 'gan_계', '계': 'gan_계'
    };
    if (ganMap[cleanKey]) {
        return MYEONGLI_ESSAY_DB[ganMap[cleanKey]] || null;
    }
    
    // 2. 오행 체크
    const elementMap: Record<string, string> = {
        '목': 'elem_목', 'wood': 'elem_목',
        '화': 'elem_화', 'fire': 'elem_화',
        '토': 'elem_토', 'earth': 'elem_토',
        '금': 'elem_금', 'metal': 'elem_금',
        '수': 'elem_수', 'water': 'elem_수'
    };
    if (elementMap[cleanKey]) {
        return MYEONGLI_ESSAY_DB[elementMap[cleanKey]] || null;
    }

    // 3. 십성 체크
    const gods = ['비견', '겁재', '식신', '상관', '편재', '정재', '편관', '정관', '편인', '정인'];
    for (const g of gods) {
        if (cleanKey.includes(g)) {
            return MYEONGLI_ESSAY_DB[`god_${g}`] || null;
        }
    }

    // 4. 12운성 체크 (단, '병'은 12운성이기도 하지만 천간 '병'도 있으므로 위에서 천간이 먼저 매핑됨. 접두사 없이 단순 '병'이 오면 일간 병화가 됨)
    const stars = ['장생', '목욕', '관대', '건록', '임관', '제왕', '쇠', '병', '사', '묘', '절', '태', '양'];
    const wunsungMap: Record<string, string> = {
        '건록': 'star_건록', '건록(임관)': 'star_건록', '임관': 'star_건록'
    };
    if (wunsungMap[cleanKey]) {
        return MYEONGLI_ESSAY_DB[wunsungMap[cleanKey]] || null;
    }
    for (const s of stars) {
        if (cleanKey.includes(s)) {
            const key = s === '임관' ? '건록' : s;
            return MYEONGLI_ESSAY_DB[`star_${key}`] || null;
        }
    }
    
    // 5. 공망 체크
    if (cleanKey.includes('공망')) {
        return MYEONGLI_ESSAY_DB['void_공망'] || null;
    }
    
    return null;
}
